/* Import an already-reviewed opaque image package; no generation or network writes. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const packageRoot = process.argv[2];
const themes = ['mushroom-forest', 'cloud-balloon', 'night-observatory', 'coral-lagoon'];

async function main() {
  if (!packageRoot)
    throw new Error('Usage: node scripts/import-house-scenes.cjs <package directory>');
  const manifest = JSON.parse(fs.readFileSync(path.join(packageRoot, 'manifest.json'), 'utf8'));
  if (manifest.version !== 1 || !Array.isArray(manifest.scenes))
    throw new Error('Unsupported manifest');
  const seen = new Set();
  const imports = [];
  for (const scene of manifest.scenes) {
    const identity = `${scene.themeId}-${scene.capacity}`;
    if (
      !themes.includes(scene.themeId) ||
      ![2, 4, 6].includes(scene.capacity) ||
      seen.has(identity)
    )
      throw new Error(`Invalid/duplicate scene ${identity}`);
    seen.add(identity);
    const basename = `${scene.themeId}-${scene.capacity}p.webp`;
    if (scene.file !== `assets/${basename}`) throw new Error(`Unexpected asset path ${scene.file}`);
    const src = path.join(packageRoot, scene.file);
    if (
      scene.sha256 &&
      crypto.createHash('sha256').update(fs.readFileSync(src)).digest('hex') !== scene.sha256
    )
      throw new Error(`Source checksum mismatch ${identity}`);
    const metadata = await sharp(src).metadata();
    if (
      metadata.width !== scene.width ||
      metadata.height !== scene.height ||
      metadata.format !== 'webp'
    )
      throw new Error(`Source dimensions/format mismatch ${identity}`);
    if (metadata.hasAlpha && !(await sharp(src).stats()).isOpaque)
      throw new Error(`Scene must be opaque ${identity}`);
    if (scene.roomRects.length !== scene.capacity)
      throw new Error(`Missing room geometry ${identity}`);
    for (const rect of scene.roomRects) {
      if (
        ![rect.x, rect.y, rect.width, rect.height, rect.radius ?? 0].every(Number.isFinite) ||
        rect.x < 0 ||
        rect.y < 0 ||
        rect.width <= 0 ||
        rect.height <= 0 ||
        rect.x + rect.width > scene.width ||
        rect.y + rect.height > scene.height
      )
        throw new Error(`Invalid aperture ${identity}`);
    }
    const dest = path.join(root, 'assets/images/house-scenes', basename);
    fs.copyFileSync(src, dest);
    imports.push(`  '${scene.file}': require('@/assets/images/house-scenes/${basename}'),`);
  }
  fs.writeFileSync(
    path.join(root, 'src/resources/house-scenes/manifest.json'),
    JSON.stringify(manifest, null, 2) + '\n',
  );
  fs.writeFileSync(
    path.join(root, 'src/resources/house-scenes/sources.ts'),
    `/** Generated by scripts/import-house-scenes.cjs. Local sources, never CDN guesses. */\nexport const HOUSE_SCENE_SOURCES: Readonly<Record<string, number>> = {\n${imports.join('\n')}\n};\n`,
  );
  process.stdout.write(`Imported ${seen.size} scenes.\n`);
}
main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
