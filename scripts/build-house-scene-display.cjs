/* Precompute the exterior alpha fade; runtime renders a normal PNG via Expo Image. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const metadataDir = path.join(root, 'src/resources/house-scenes/display');
const imageDir = path.join(root, 'assets/images/house-scenes/display');
const scenes = JSON.parse(
  fs.readFileSync(path.join(root, 'src/resources/house-scenes/manifest.json')),
).scenes;
const sha256 = (data) => crypto.createHash('sha256').update(data).digest('hex');
const feather = 64;

function axisAlpha(position, start, end, size) {
  if (position < start)
    return Math.max(0, (position - Math.max(0, start - feather)) / Math.min(start, feather));
  if (position >= end)
    return Math.max(0, (Math.min(size, end + feather) - position) / Math.min(size - end, feather));
  return 1;
}

async function main() {
  fs.mkdirSync(metadataDir, { recursive: true });
  fs.mkdirSync(imageDir, { recursive: true });
  const entries = [];
  for (const scene of scenes) {
    const original = path.join(root, 'assets/images/house-scenes', path.basename(scene.file));
    if (sha256(fs.readFileSync(original)) !== scene.sha256)
      throw new Error(`Source hash mismatch: ${scene.file}`);
    const { data: rgb, info } = await sharp(original)
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    const roi = scene.protectedRect;
    if (
      !roi ||
      roi.x <= 0 ||
      roi.y <= 0 ||
      roi.x + roi.width >= info.width ||
      roi.y + roi.height >= info.height
    )
      throw new Error(`Invalid protected region: ${scene.file}`);
    const rgba = Buffer.alloc(info.width * info.height * 4);
    let protectedPixels = 0;
    for (let y = 0; y < info.height; y++) {
      for (let x = 0; x < info.width; x++) {
        const index = y * info.width + x;
        rgb.copy(rgba, index * 4, index * 3, index * 3 + 3);
        const inside = x >= roi.x && x < roi.x + roi.width && y >= roi.y && y < roi.y + roi.height;
        const alpha = Math.round(
          255 *
            axisAlpha(x + 0.5, roi.x, roi.x + roi.width, info.width) *
            axisAlpha(y + 0.5, roi.y, roi.y + roi.height, info.height),
        );
        rgba[index * 4 + 3] = alpha;
        if (inside) {
          if (alpha !== 255) throw new Error(`Protected pixel faded: ${scene.file}`);
          protectedPixels++;
        }
      }
    }
    const basename = `${scene.themeId}-${scene.capacity}p.png`;
    const png = await sharp(rgba, { raw: { width: info.width, height: info.height, channels: 4 } })
      .png({ compressionLevel: 9, adaptiveFiltering: true })
      .toBuffer();
    const decoded = await sharp(png).ensureAlpha().raw().toBuffer();
    if (!decoded.equals(rgba)) throw new Error(`PNG pixel roundtrip failed: ${scene.file}`);
    fs.writeFileSync(path.join(imageDir, basename), png);
    entries.push({
      sceneFile: scene.file,
      file: basename,
      themeId: scene.themeId,
      capacity: scene.capacity,
      width: info.width,
      height: info.height,
      bytes: png.length,
      sha256: sha256(png),
      sourceSha256: scene.sha256,
      protectedPixels,
      protectedAlpha: 255,
      originalRgbPreserved: true,
      pngPixelRoundtripVerified: true,
    });
  }
  fs.writeFileSync(
    path.join(metadataDir, 'manifest.json'),
    JSON.stringify({ version: 1, featherPixels: feather, entries }, null, 2) + '\n',
  );
  fs.writeFileSync(
    path.join(metadataDir, 'sources.ts'),
    `/** Generated by scripts/build-house-scene-display.cjs. */\nexport const HOUSE_SCENE_DISPLAY_SOURCES: Readonly<Record<string, number>> = {\n${entries.map((entry) => `  '${entry.sceneFile}': require('@/assets/images/house-scenes/display/${entry.file}'),`).join('\n')}\n};\n`,
  );
  process.stdout.write(
    JSON.stringify({
      count: entries.length,
      totalBytes: entries.reduce((total, entry) => total + entry.bytes, 0),
      protectedAlpha: 255,
      originalRgbPreserved: true,
    }) + '\n',
  );
}
main().catch((error) => {
  process.stderr.write(error.message + '\n');
  process.exitCode = 1;
});
